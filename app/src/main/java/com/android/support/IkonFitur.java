    @Override
    protected void onMeasure(int widthMeasureSpec, int heightMeasureSpec) {
        int sisi = (int) Theme.dp(getContext(), 40f);
        setMeasuredDimension(resolveSize(sisi, widthMeasureSpec),
                resolveSize(sisi, heightMeasureSpec));
    }

    @Override
    protected void onDraw(Canvas canvas) {
        float lebar = getWidth();
        float tinggi = getHeight();
        float radius = Theme.dp(getContext(), Theme.RADIUS_IKON);

        // Kotak ikon menempel di tepi kiri baris, jadi hanya sisi kiri yang
        // melengkung. Sisi kanan siku supaya menyatu dengan latar baris.
        float[] sudut = sudutKiri
                ? new float[]{radius, radius, radius, radius, 0f, 0f, 0f, 0f}
                : new float[]{radius, radius, radius, radius, radius, radius, radius, radius};

        cat.setAntiAlias(true);
        cat.setStyle(Paint.Style.FILL);
        cat.setColor(Theme.ICON_BOX);
        Path kotak = new Path();
        kotak.addRoundRect(new RectF(0f, 0f, lebar, tinggi), sudut, Path.Direction.CW);
        canvas.drawPath(kotak, cat);

        float tebal = Theme.dp(getContext(), 1f);
        cat.setStyle(Paint.Style.STROKE);
        cat.setStrokeWidth(tebal);
        cat.setColor(Theme.OUTLINE);
        canvas.drawPath(kotak, cat);

        gambarPola(canvas, lebar, tinggi);
    }

    private void gambarPola(Canvas canvas, float lebar, float tinggi) {
        if (pola == null || pola.length == 0)
            return;

        // Satu sel selalu bilangan bulat piksel supaya tidak ada setengah piksel
        // yang membuat tepi ikon tampak kabur.
        float sel = (float) Math.floor(Math.min(lebar, tinggi) / 18.0);
        if (sel < 1f)
            sel = 1f;

        float lebarIkon = sel * 16f;
        float kiri = (lebar - lebarIkon) / 2f;
        float atas = (tinggi - sel * pola.length) / 2f;

        cat.setAntiAlias(false);
        cat.setStyle(Paint.Style.FILL);
        for (int y = 0; y < pola.length; y++) {
            String baris = pola[y];
            for (int x = 0; x < baris.length(); x++) {
                char isi = baris.charAt(x);
                if (isi == KOSONG)
                    continue;
                cat.setColor(isi == TERANG ? Theme.TITLE_TEXT : Theme.TAN);
                canvas.drawRect(kiri + x * sel, atas + y * sel,
                        kiri + (x + 1) * sel, atas + (y + 1) * sel, cat);
            }
        }
        cat.setAntiAlias(true);
    }
